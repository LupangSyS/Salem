let seq = 0;
function buildDeck() {
  const deck = [];
  for (const [type, c] of Object.entries(CARDS)) {
    for (let i = 0; i < c.count; i++) deck.push({ id: ++seq, type });
  }
  return deck;
}
const DECK_SIZE = Object.values(CARDS).reduce((s, c) => s + c.count, 0);

/** การ์ดไต่สวนสำหรับผู้เล่น n คน */
function buildTryals(n) {
  const [per, witches] = TRYAL_TABLE[n];
  const kinds = [];
  for (let i = 0; i < witches; i++) kinds.push('w');
  kinds.push('c');
  while (kinds.length < per * n) kinds.push('nw');
  return kinds;
}

const typeLine = (type) => {
  const c = CARDS[type];
  if (c.color === 'red') return `${COLORS.red.name} · กล่าวหา +${c.value}`;
  if (c.color === 'green') return `${COLORS.green.name} · ทันที`;
  if (c.color === 'blue') return `${COLORS.blue.name} · ถาวร`;
  return `${COLORS.black.name} · เหตุการณ์`;
};

